#!/usr/bin/env python3
"""Spring easings for the web app's motion (Material 3 Expressive), as CSS custom properties.

CSS has no spring timing function, but linear() takes sampled points, so each token is a damped
spring (mass 1) sampled from its stiffness and damping ratio:

    x(t) = 1 - e^(-ζωt) (cos ωd t + (ζω/ωd) sin ωd t),   ω = sqrt(stiffness), ωd = ω sqrt(1-ζ²)

Spatial springs (position, size, shape) may overshoot; effects springs (opacity, colour) do not.
Values are the Material 3 Expressive motion scheme. Output: backend/app/static/css/motion-tokens.css
Run:  python3 scripts/gen_motion_tokens.py
"""
import math
from pathlib import Path

SPRINGS = {   # name: (damping ratio, stiffness)
    "spatial-fast": (0.6, 800), "spatial-default": (0.8, 380), "spatial-slow": (0.8, 200),
    "effects-fast": (1.0, 3800), "effects-default": (1.0, 1600), "effects-slow": (1.0, 800),
}


def step(t, zeta, k):
    w = math.sqrt(k)
    if zeta >= 1:
        return 1 - math.exp(-w * t) * (1 + w * t)
    wd = w * math.sqrt(1 - zeta * zeta)
    return 1 - math.exp(-zeta * w * t) * (math.cos(wd * t) + (zeta * w / wd) * math.sin(wd * t))


def settle_time(zeta, k, eps=0.002):
    t, last = 0.0, 0.0
    while t < 10:
        t += 0.002
        if abs(1 - step(t, zeta, k)) > eps:
            last = t
    return last + 0.002


def token(zeta, k, points=36):
    T = settle_time(zeta, k)
    ys = [round(step(T * i / points, zeta, k), 4) for i in range(points + 1)]
    ys[0], ys[-1] = 0, 1
    return round(T * 1000), "linear(" + ", ".join(f"{y:g}" for y in ys) + ")"


lines = ["/* Generated by scripts/gen_motion_tokens.py: do not edit by hand.",
         "   Material 3 Expressive springs sampled into CSS linear() easings. */", ":root {"]
for name, (zeta, k) in SPRINGS.items():
    ms, ease = token(zeta, k)
    lines.append(f"  --dur-{name}: {ms}ms;")
    lines.append(f"  --ease-{name}: {ease};")
lines.append("}")
out = Path(__file__).resolve().parents[1] / "backend/app/static/css/motion-tokens.css"
out.write_text("\n".join(lines) + "\n")
print(f"wrote {out}")
for name, (zeta, k) in SPRINGS.items():
    print(f"  {name:16} ζ={zeta} k={k}: {token(zeta, k)[0]} ms")
