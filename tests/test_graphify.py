"""Contract tests for the keyless Graphify generation and GitHub automation."""
from __future__ import annotations

import json
import re
import shutil
import subprocess

import pytest
import yaml

from conftest import ROOT

WORKFLOW = ROOT / ".github/workflows/graphify.yml"
OUT = ROOT / "graphify-out"


def _workflow():
    return yaml.safe_load(WORKFLOW.read_text())


def _on(workflow):
    return workflow.get("on", workflow.get(True))


def test_official_graphify_cli_is_available_when_graph_workflow_runs():
    executable = shutil.which("graphify")
    if not executable:
        pytest.skip("Graphify is installed by the dedicated graph workflow")
    assert re.match(r"graphify \d+\.\d+\.\d+", subprocess.check_output([executable, "--version"], text=True))


def test_generated_graph_is_valid_meaningful_and_covers_impress_components():
    required = [OUT / "graph.json", OUT / "graph.html", OUT / "GRAPH_REPORT.md"]
    if not all(path.exists() for path in required):
        pytest.skip("graph output is generated by the dedicated graph workflow")
    assert all(path.stat().st_size > 0 for path in required)
    graph = json.loads((OUT / "graph.json").read_text())
    assert len(graph["nodes"]) >= 100 and len(graph["links"]) >= 100
    labels = {node.get("label") for node in graph["nodes"]}
    assert {"Python/FastAPI backend", "Frontend", "ESP32 firmware", "REST API", "WebSocket live session protocol", "SPI framed batch protocol"} <= labels
    assert {edge["relation"] for edge in graph["links"]} >= {"contains", "implements", "calls", "imports"}


def test_generated_output_has_no_local_paths_or_secret_values():
    if not OUT.exists():
        pytest.skip("graph output is generated by the dedicated graph workflow")
    text = "\n".join((OUT / name).read_text(errors="replace") for name in ("graph.json", "graph.html", "GRAPH_REPORT.md"))
    assert str(ROOT) not in text
    assert not re.search(r"(?:gh[pousr]_[A-Za-z0-9]{20,}|github_pat_|sk-[A-Za-z0-9]{20,}|BEGIN (?:RSA |EC )?PRIVATE KEY)", text)


def test_workflow_has_required_trigger_permissions_cache_and_recursion_guards():
    workflow, on = _workflow(), _on(_workflow())
    assert on["push"]["branches"] == ["varun/v2.1"]
    assert "graphify-out/**" in on["push"]["paths-ignore"]
    assert "workflow_dispatch" in on
    assert workflow["permissions"] == {"contents": "write", "pull-requests": "write"}
    assert workflow["concurrency"]["cancel-in-progress"] is False
    job = workflow["jobs"]["generate"]
    assert "github-actions[bot]" in job["if"]
    steps = "\n".join(str(step) for step in job["steps"])
    assert "graphifyy==" in steps and "scripts/validate_graphify.py" in steps
    assert "actions/cache@" in steps and "SOURCE_SHA" in steps
    assert "git diff --quiet -- graphify-out" in steps and "gh pr create" in steps


def test_workflow_actions_are_pinned_and_generation_is_before_publish():
    text = WORKFLOW.read_text()
    for action, sha in re.findall(r"uses:\s*([^@\s]+)@([0-9a-f]+)", text):
        assert len(sha) == 40, f"{action} is not pinned to a full commit SHA"
    assert text.index("Generate the complete") < text.index("Publish only")
